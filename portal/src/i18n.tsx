const dict = { ...baseDict, ...manageDict, ...birthsDict };

export type Key = keyof typeof dict;

interface I18n {
  lang: Lang;
  setLang: (l: Lang) => void;
  t: (k: Key, vars?: Record<string, string | number>) => string;
  /** pick the right language from an API-provided bilingual object */
  b: (v: Bi | null | undefined) => string;
  fmtDate: (iso: string | number | Date | null | undefined, withTime?: boolean) => string;
}

const Ctx = createContext<I18n | null>(null);

function initialLang(): Lang {
  try {
    const saved = localStorage.getItem('sarab.lang');
    if (saved === 'ar' || saved === 'en') return saved;
  } catch { /* storage unavailable */ }
  return 'ar';
}

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(initialLang);
  useEffect(() => {
    document.documentElement.lang = lang;
    document.documentElement.dir = lang === 'ar' ? 'rtl' : 'ltr';
    try { localStorage.setItem('sarab.lang', lang); } catch { /* ignore */ }
  }, [lang]);
  const value = useMemo<I18n>(() => ({
    lang,
    setLang: setLangState,
    t: (k, vars) => {
      let s = dict[k][lang];
      if (vars) for (const [n, v] of Object.entries(vars)) s = s.replaceAll(`{${n}}`, String(v));
      return s;
    },
    b: (v) => (v ? v[lang] ?? v.en : ''),
    fmtDate: (iso, withTime = false) => {
      if (iso === null || iso === undefined || iso === '') return '';
      const d = typeof iso === 'number' ? new Date(iso * 1000) : new Date(iso);
      return new Intl.DateTimeFormat(lang === 'ar' ? 'ar-u-nu-latn' : 'en-GB', {
        dateStyle: 'medium', ...(withTime ? { timeStyle: 'short' } : {}),
      }).format(d);
    },
  }), [lang]);
  return <Ctx.Provider value={value}>{children}</Ctx.Provider>;
}

export function useI18n(): I18n {
  const v = useContext(Ctx);
  if (!v) throw new Error('I18nProvider missing');
  return v;
}

export function hasKey(k: string): k is Key {
  return k in dict;
}
